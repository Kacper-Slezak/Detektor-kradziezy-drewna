"""Inspect YAMNet versus existing TinyML continuous inference CSV on a WAV.

Run in .venv-yamnet (Python 3.11). Scores are not calibrated probabilities.
Teacher scores are aggregated like v4_2_teacher.py: top 2 patches per
2-second student window, with 16 kHz original audio as input.
"""
from __future__ import annotations
import argparse
import csv
import tempfile
import subprocess
from pathlib import Path

import numpy as np
from algorithm.app.v4_2_teacher import ENGINE_CLASSES, load_audio


def teacher_scores_for_windows(centers, chosen, student_rows):
    outputs = []
    for row in student_rows:
        t = float(row['time_s'])
        end = float(row['window_end_s'])
        selected = chosen[(centers >= t) & (centers < end)]
        if not len(selected):
            selected = chosen[np.argmin(abs(centers - (t+end)/2)):
                              np.argmin(abs(centers - (t+end)/2))+1]
        outputs.append(float(np.mean(sorted(selected, reverse=True)[:2])))
    return outputs


def run(args):
    with args.student_csv.open(newline='',encoding='utf-8-sig') as f:
        rows = list(csv.DictReader(f))
    required = {'time_s','window_end_s','ml_engine_score'}
    if not rows or not required.issubset(rows[0]):
        raise ValueError('Expected --student-csv generated by v4_2_infer')
    if not args.audio_wav.is_file():
        raise FileNotFoundError(args.audio_wav)
    # Lazy imports keep helpers testable without TensorFlow.
    import tensorflow as tf
    import tensorflow_hub as hub
    model = hub.load(args.hub_url)
    with open(model.class_map_path().numpy().decode('utf-8'),
              newline='', encoding='utf-8') as f:
        names = [r['display_name'] for r in csv.DictReader(f)]
    picks = [(name,names.index(name)) for name in ENGINE_CLASSES if name in names]
    if not picks:
        raise RuntimeError('No engine/vehicle classes found in YAMNet class map')
    with tempfile.TemporaryDirectory() as td:
        wav16 = Path(td)/'teacher_16k.wav'
        cmd = ['ffmpeg','-nostdin','-hide_banner','-loglevel','error','-y',
               '-i',str(args.audio_wav),'-ac','1','-ar','16000',
               '-c:a','pcm_s16le',str(wav16)]
        result = subprocess.run(cmd,capture_output=True,text=True)
        if result.returncode:
            raise RuntimeError('FFmpeg failed: '+result.stderr[-1200:])
        audio = load_audio(wav16)
        scores, _, _ = model(tf.convert_to_tensor(audio, dtype=tf.float32))
        scores = np.asarray(scores.numpy(), dtype=np.float32)
    centers = np.arange(len(scores), dtype=np.float32)*0.48+0.48
    chosen = scores[:,[i for _,i in picks]].max(axis=1)
    values = teacher_scores_for_windows(centers,chosen,rows)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    fields = ['time_s','window_end_s','tinyml_score','yamnet_engine_score',
              'score_difference','tinyml_detected','tinyml_confirmed']
    with args.output.open('w',newline='',encoding='utf-8') as f:
        wr = csv.DictWriter(f,fieldnames=fields)
        wr.writeheader()
        for row,teach in zip(rows,values):
            student = float(row['ml_engine_score']) if row['ml_engine_score'] not in ('','None') else float('nan')
            wr.writerow(dict(time_s=row['time_s'],window_end_s=row['window_end_s'],
                             tinyml_score=round(student,5),yamnet_engine_score=round(teach,5),
                             score_difference=round(student-teach,5),
                             tinyml_detected=row.get('engine_detected',''),
                             tinyml_confirmed=row.get('engine_confirmed','')))
    print('YAMNet classes:',', '.join(n for n,_ in picks))
    print('Windows:',len(rows),'Teacher mean:',round(float(np.mean(values)),4),
          'Teacher max:',round(float(np.max(values)),4))
    if args.engine_start is not None:
        if args.engine_end is None or args.engine_end <= args.engine_start:
            raise ValueError('Provide --engine-end after --engine-start')
        inside = [s for r,s in zip(rows,values)
                  if args.engine_start <= (float(r['time_s']) + float(r['window_end_s']))/2 < args.engine_end]
        outside = [s for r,s in zip(rows,values)
                   if not args.engine_start <= (float(r['time_s']) + float(r['window_end_s']))/2 < args.engine_end]
        print('Teacher within ENGINE:',round(float(np.mean(inside)),4) if inside else 'n/a',
              'outside:',round(float(np.mean(outside)),4) if outside else 'n/a')
    print('CSV:',args.output)
    print('Teacher raw scores are not directly calibrated against TinyML scores.')


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--audio-wav',type=Path,required=True)
    p.add_argument('--student-csv',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--hub-url',default='https://tfhub.dev/google/yamnet/1')
    p.add_argument('--engine-start',type=float)
    p.add_argument('--engine-end',type=float)
    run(p.parse_args())


if __name__=='__main__':
    main()
